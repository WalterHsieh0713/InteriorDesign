// Finds IKEA's own glTF model for each catalog item and records its URL.
//
// IKEA ships these to power the "View in 3D" button on its product pages, and
// they are the exact assets its AR app uses — so they are physically correct to
// the millimetre, which no stand-in mesh can be. A MICKE desk measures
// 1.050 x 0.756 x 0.502 against a product page stating 1.051 x 0.749 x 0.498.
//
//   node scripts/fetch-ikea-models.mjs
//
// It records URLs, it does NOT download geometry. The bytes are fetched
// server-side at request time by /api/ikea-model, so no IKEA asset is ever
// copied into this repo. See EDITOR_INTEGRATION.md on why that distinction
// matters for a public repository.
import { readFileSync, writeFileSync } from "node:fs";

const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36";

const rd = (p, re) => JSON.parse(readFileSync(p, "utf8").match(re)[1]);
const generated = rd("src/lib/catalog.generated.ts", /= (\[[\s\S]*\]);/);
const manual = (() => {
  try { return rd("src/lib/catalog.manual.ts", /MANUAL_ITEMS: CatalogItem\[\] = (\[[\s\S]*\]);/); }
  catch { return []; }
})();

// Hand-authored rows win, exactly as catalog.ts merges them.
const byId = new Map();
for (const i of generated) byId.set(i.id, i);
for (const i of manual) byId.set(i.id, i);
const items = [...byId.values()].filter((i) => i.productUrl?.includes("ikea.com"));

const found = {};
let hits = 0, misses = [];

for (const item of items) {
  try {
    const res = await fetch(item.productUrl, { headers: { "User-Agent": UA } });
    if (!res.ok) { misses.push(`${item.name} (HTTP ${res.status})`); continue; }
    const html = await res.text();

    // Prefer the Draco build: same geometry, a fraction of the bytes, and the
    // loader already has a decoder wired up.
    const urls = [...html.matchAll(/https?:\/\/web-api\.ikea\.com\/[^"'\ ]+\.glb/g)].map((m) => m[0]);
    const draco = urls.find((u) => u.includes("/glb_draco/"));
    const plain = urls.find((u) => !u.includes("/glb_draco/"));
    const url = draco ?? plain;

    if (!url) { misses.push(`${item.name} (no 3D model on the page)`); continue; }
    found[item.id] = url;
    hits++;
    console.log(`+ ${item.name.slice(0, 34).padEnd(34)} ${draco ? "draco" : "plain"}`);
  } catch (e) {
    misses.push(`${item.name} (${e.message.split("\n")[0]})`);
  }
}

writeFileSync(
  "src/lib/ikeaModels.generated.ts",
  `// GENERATED by scripts/fetch-ikea-models.mjs — do not edit by hand.
// Built ${new Date().toISOString().slice(0, 10)}.
//
// IKEA's own glTF for each product, by catalog id. These are URLs, not files:
// nothing is downloaded into this repo, and /api/ikea-model fetches the bytes
// server-side because web-api.ikea.com rejects any request carrying a browser
// Origin header.
//
// URLs contain a content hash and change when IKEA updates a model, so re-run
// this if a product stops rendering.

export const IKEA_MODEL_URLS: Record<string, string> = ${JSON.stringify(found, null, 2)};
`
);

console.log(`\n${hits}/${items.length} IKEA products have a real 3D model`);
if (misses.length) {
  console.log(`${misses.length} without one:`);
  for (const m of misses) console.log(`  - ${m}`);
}
